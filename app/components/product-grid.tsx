export default function ProductGrid({ category }: { category?: string }) {
  // Filter products by category if provided
  const filteredProducts = category ? products.filter((product) => product.category === category) : products

  return (
    <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-6 transition-colors duration-200">
      {filteredProducts.map((product) => (
        <div key={product.id} className="group">
          <div className="aspect-square relative mb-4 overflow-hidden rounded-lg">
            <Image
              src={product.image || "/placeholder.svg"}
              alt={product.name}
              fill
              className="object-cover transition-transform duration-300 group-hover:scale-105"
            />
            <div className="absolute inset-x-0 bottom-0 p-4 opacity-0 group-hover:opacity-100 transition-opacity">
              <Button className="w-full" size="sm">
                Add to Cart
              </Button>
            </div>
          </div>
          <Link href={product.href} className="block">
            <h3 className="text-lg font-medium mb-1">{product.name}</h3>
            <div className="flex items-center mb-2">
              <div className="flex items-center">
                {[...Array(5)].map((_, i) => (
                  <Star
                    key={i}
                    className={`h-4 w-4 ${
                      i < Math.floor(product.rating)
                        ? "text-yellow-400 fill-yellow-400"
                        : "text-gray-300 dark:text-gray-600"
                    }`}
                  />
                ))}
              </div>
              <span className="text-sm text-gray-500 dark:text-gray-400 ml-2">({product.reviewCount})</span>
            </div>
            <p className="text-lg font-medium">${product.price}</p>
          </Link>
        </div>
      ))}
    </div>
  )
}
